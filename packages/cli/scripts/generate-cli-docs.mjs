#!/usr/bin/env node
/**
 * Regenerates `docs/CLI.md` from the CLI's own `--help` output.
 *
 * Run `npm run docs:generate` from `packages/cli`. Every page comes from
 * `run([...path, "--help"])`, so the reference cannot describe a flag that
 * the CLI does not accept. A test checks that the committed file is current.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { run } from "../dist/cli.js";
import { HELP_PATHS } from "../dist/help.js";

const OUTPUT = fileURLToPath(new URL("../../../docs/CLI.md", import.meta.url));

/** Renders the whole reference. Exported so a test can compare it without writing. */
export async function renderReference() {
  const lines = [
    "# `skn` command reference",
    "",
    "<!-- Generated by `npm run docs:generate` in packages/cli. Do not edit by hand. -->",
    "",
    "Every section below is the output of `skn <command> --help`. For a guided",
    "walkthrough, see the [quickstart](../packages/cli/README.md#quickstart).",
    "",
  ];

  for (const path of HELP_PATHS) {
    const result = await run([...path, "--help"]);
    const label = path.length === 0 ? "" : ` ${path.join(" ")}`;
    if (result.exitCode !== 0 || result.stderr !== "") {
      throw new Error(`skn${label} --help failed: ${result.stderr || `exit ${result.exitCode}`}`);
    }
    lines.push(`## \`skn${label}\``, "", "```text", result.stdout.trimEnd(), "```", "");
  }
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writeFile(OUTPUT, await renderReference(), "utf8");
  process.stdout.write(`Wrote ${OUTPUT}\n`);
}
