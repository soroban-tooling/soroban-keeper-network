import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { EXIT } from "../src/exitCodes.js";
import { ADMIN_COMMANDS } from "../src/commands/admin/index.js";
import { KEEPER_COMMANDS } from "../src/commands/keeper/index.js";
import { TASK_COMMANDS } from "../src/commands/task/index.js";
import { run } from "../src/cli.js";
import { HELP_PATHS, helpFor } from "../src/help.js";

const label = (path: readonly string[]) => (path.length === 0 ? "" : ` ${path.join(" ")}`);

describe("CLI help and generated reference", () => {
  it("answers --help for every catalogue path without touching the network", async () => {
    for (const path of HELP_PATHS) {
      const result = await run([...path, "--help"]);
      expect(result.exitCode, `skn${label(path)} --help`).toBe(EXIT.ok);
      expect(result.stderr, `skn${label(path)} --help`).toBe("");
      expect(result.stdout).toContain("Usage:");
      expect(result.stdout).toContain("Global flags (accepted by every command):");
      expect(result.stdout).toBe(helpFor(path));
    }
  });

  it("documents every implemented subcommand", () => {
    const documented = new Set(HELP_PATHS.map((path) => path.join(" ")));
    for (const command of TASK_COMMANDS) expect(documented.has(`task ${command}`)).toBe(true);
    for (const command of KEEPER_COMMANDS) expect(documented.has(`keeper ${command}`)).toBe(true);
    for (const command of ADMIN_COMMANDS) expect(documented.has(`admin ${command}`)).toBe(true);
  });

  it("keeps docs/CLI.md in sync with --help", async () => {
    const doc = await readFile(
      fileURLToPath(new URL("../../../docs/CLI.md", import.meta.url)),
      "utf8",
    );
    expect(doc).toContain("Generated by `npm run docs:generate`");
    for (const path of HELP_PATHS) {
      const help = helpFor(path);
      expect(help, `help page for skn${label(path)}`).toBeDefined();
      expect(doc).toContain(`## \`skn${label(path)}\``);
      expect(doc, `skn${label(path)} --help in docs/CLI.md`).toContain(help?.trimEnd());
    }
  });
});
